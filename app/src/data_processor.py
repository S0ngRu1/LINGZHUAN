def process_work_data() -> pd.DataFrame:
    """
    处理工作数据：计算持续天数、关联阶段颜色
    :return: 处理后的DataFrame
    """
    # 加载原始数据
    raw_data = load_work_data()
    # 转换为DataFrame
    df = pd.DataFrame(raw_data)
    
    # 计算持续天数（结束日 - 开始日 + 1，确保1天任务持续天数为1）
    df["持续天数"] = df["结束日"] - df["开始日"] + 1
    
    # 关联阶段颜色（从配置文件获取）
    df["阶段颜色（十六进制）"] = df["阶段"].map(STAGE_COLOR_MAP)
    
    # 验证数据完整性（检查是否有未匹配颜色的阶段）
    missing_color_stages = df[df["阶段颜色（十六进制）"].isna()]["阶段"].unique()
    if len(missing_color_stages) > 0:
        logger.warning(f"以下阶段未配置颜色：{list(missing_color_stages)}，请检查config/color_config.py")
    
    logger.info("工作数据处理完成，新增「持续天数」「阶段颜色（十六进制）」字段")
    return df